type BatchLineFixture = Omit<
  StockBatchLineDetailResponse,
  'id' | 'stockBatchId' | 'createdAt' | 'updatedAt'
>;

type BatchFixture = Omit<
  StockBatchDetailResponse,
  | 'businessId'
  | 'branchId'
  | 'confirmedAt'
  | 'receivedByMemberId'
  | 'lines'
  | 'createdAt'
  | 'updatedAt'
> & {
  lines: BatchLineFixture[];
};

const makeBatch = ({ lines, ...batch }: BatchFixture): StockBatchDetailResponse => ({
  ...batch,
  businessId: BUSINESS_ID,
  branchId: BRANCH_ID,
  confirmedAt: batch.batchDate,
  receivedByMemberId: batch.receivedBy?.id ?? null,
  lines: lines.map((line, index) => ({
    ...line,
    id: `${batch.id}_line_${index + 1}`,
    stockBatchId: batch.id,
    createdAt: FIXTURE_TIMESTAMP,
    updatedAt: FIXTURE_TIMESTAMP,
  })),
  createdAt: FIXTURE_TIMESTAMP,
  updatedAt: FIXTURE_TIMESTAMP,
});

